  (function renderRegimento() {
    const container = document.getElementById('regimento-accordion');
    container.innerHTML = REGIMENTO.map((secao, i) => `
      <div class="card" style="margin-bottom:12px;padding:0;overflow:hidden">
        <button onclick="toggleRegimento(${i})" style="
          width:100%;display:flex;align-items:center;justify-content:space-between;
          padding:14px 18px;background:none;border:none;cursor:pointer;
          color:var(--text);font-size:0.95rem;font-weight:600;text-align:left;gap:12px
        ">
          <span>${secao.titulo}</span>
          <span id="reg-chevron-${i}" style="color:${secao.cor};font-size:1.1rem;transition:transform 0.2s">▸</span>
        </button>
        <div id="reg-body-${i}" style="display:none;border-top:1px solid var(--border);padding:14px 18px 16px">
          <ul style="margin:0;padding-left:18px;display:flex;flex-direction:column;gap:8px">
            ${secao.itens.map(item => `<li style="font-size:0.87rem;color:var(--text-muted);line-height:1.5">${item}</li>`).join('')}
          </ul>
        </div>
      </div>
    `).join('');
  })();

  function toggleRegimento(i) {
    const body = document.getElementById(`reg-body-${i}`);
    const chevron = document.getElementById(`reg-chevron-${i}`);
    const open = body.style.display !== 'none';
    body.style.display = open ? 'none' : 'block';
    chevron.style.transform = open ? '' : 'rotate(90deg)';
  }
